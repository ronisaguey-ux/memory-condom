"use strict";
/**
 * Markdown bridge: import an existing AGENTS.md into records, and render records back to a
 * deterministic AGENTS.md.
 *
 * Rendering must be byte-stable. The provider caches an exact prefix, so the same store has to
 * produce the same file every time — insertion order, no sorting, no timestamps of "now".
 */

const { LIMITS, slugTopic, readStore, resolve } = require("./store.js");

function splitSentences(text, max) {
  const out = [];
  let cur = "";
  for (const piece of text.split(/(?<=[.!?])\s+/)) {
    if (!piece) continue;
    if ((cur + " " + piece).trim().length <= max) cur = (cur + " " + piece).trim();
    else {
      if (cur) out.push(cur);
      if (piece.length <= max) cur = piece;
      else {
        out.push(...hardSplit(piece, max));
        cur = "";
      }
    }
  }
  if (cur) out.push(cur);
  return out.flatMap((s) => (s.length > max ? hardSplit(s, max) : [s]));
}

function hardSplit(text, max) {
  const parts = [];
  let rest = text;
  while (rest.length > max) {
    let cut = rest.lastIndexOf(" ", max);
    if (cut < max * 0.5) cut = max;
    parts.push(rest.slice(0, cut).trim());
    rest = rest.slice(cut).trim();
  }
  if (rest) parts.push(rest);
  return parts;
}

/** Heading -> topic slug, cut on a word boundary so the header never ends mid-word. */
function slug(s) {
  return String(s)
    .toLowerCase()
    .replace(/[`*_]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, LIMITS.topic)
    .replace(/-[^-]*$/, "")
    .replace(/-+$/, "");
}

/**
 * One record per bullet or table row: a bullet is the unit of memory, so merging a whole section
 * into a paragraph would destroy exactly the structure this store exists to keep.
 */
function importMarkdown(text, { topic = "general", ts } = {}) {
  const records = [];
  let current = slugTopic(topic);
  let buf = "";
  let inFence = false;

  const push = () => {
    const value = buf.replace(/\s+/g, " ").trim();
    buf = "";
    if (!value) return;
    if (/^[\s\-:|]+$/.test(value)) return; // table rules and separators carry no fact
    for (const part of value.length <= LIMITS.text ? [value] : splitSentences(value, LIMITS.text)) {
      records.push({
        id: "m" + String(records.length + 1).padStart(4, "0"),
        ts: ts || new Date().toISOString().slice(0, 10),
        topic: current,
        text: part,
      });
    }
  };

  for (const raw of text.split("\n")) {
    const line = raw.trimEnd();
    if (/^\s*```/.test(line)) {
      push();
      inFence = !inFence;
      continue;
    }
    if (inFence) {
      if (line.trim()) {
        push();
        buf = line.trim();
        push();
      }
      continue;
    }
    const heading = /^(#{1,6})\s+(.*)$/.exec(line);
    if (heading) {
      push();
      current = slug(heading[2]) || current;
      continue;
    }
    if (!line.trim()) {
      push();
      continue;
    }
    if (/^\s*<!--[\s\S]*-->\s*$/.test(line)) continue; // generator notes are not memories
    if (/^\s*\|?[\s:-]*-{3,}[\s:|-]*$/.test(line)) continue; // table separator
    const isBullet = /^\s*(?:[-*+]\s+|\d+[.)]\s+|\|\s*)/.test(line);
    const cleaned = line
      .replace(/^\s*(?:[-*+]\s+|\d+[.)]\s+|\|\s*)/, "")
      .replace(/\s*\|\s*/g, " — ")
      .replace(/\*\*/g, "")
      .replace(/`/g, "")
      .trim();
    if (isBullet) {
      push();
      buf = cleaned;
    } else buf = buf ? `${buf} ${cleaned}` : cleaned;
  }
  push();
  return records;
}

/** Deterministic markdown view of the live records. */
function renderMarkdown(file) {
  const records = resolve(readStore(file));
  const lines = ["<!-- generated by memory-condom from AGENTS.jsonl — edit the store, not this file -->", ""];
  let current = null;
  for (const r of records) {
    if (r.topic !== current) {
      current = r.topic;
      lines.push(`## ${current}`, "");
    }
    const tags = r.tags && r.tags.length ? ` _(${r.tags.join(", ")})_` : "";
    // id and date live in a comment so the fact itself is the first thing the model reads
    lines.push(`- ${r.text}${tags}  <!--${r.id} ${r.ts || ""}-->`);
  }
  lines.push("");
  return lines.join("\n");
}

/**
 * Import splits long bullets; a fragment that ends without sentence punctuation is the front half
 * of the next record. Join them where they fit, once, at migration time.
 */
function mergeFragments(records) {
  const out = [];
  let joined = 0;
  for (const r of records) {
    const prev = out[out.length - 1];
    const canJoin =
      prev &&
      !prev.op &&
      !r.op &&
      prev.topic === r.topic &&
      !/[.!?:;]$/.test((prev.text || "").trim()) &&
      prev.text.length + 1 + r.text.length <= LIMITS.text;
    if (canJoin) {
      prev.text = `${prev.text} ${r.text}`.replace(/\s+/g, " ").trim();
      joined++;
    } else out.push({ ...r });
  }
  return { records: out, joined };
}

/** Byte-stable size estimate. DeepSeek tokenises markdown at roughly 3.6 bytes/token. */
function estimateTokens(bytes) {
  return Math.ceil(bytes / 3.6);
}

function renderTokens(file) {
  return estimateTokens(Buffer.byteLength(renderMarkdown(file), "utf8"));
}

function budget() {
  return parseInt(process.env.MEMCONDOM_MAX_TOKENS || "12000", 10);
}

module.exports = {
  importMarkdown,
  renderMarkdown,
  mergeFragments,
  slug,
  splitSentences,
  hardSplit,
  estimateTokens,
  renderTokens,
  budget,
};
